// The seventy-seven references, once. Run by a human, output committed, never
// run again.
//
// IT REFUSES BEFORE IT WRITES. Every reference it is about to rewrite must
// name a key that image-manifest.json marks with a `verifiedAt` -- meaning
// scripts/migrate-images.mjs fetched it from the production CDN, refused it
// unless the bytes were a complete RIFF WEBP, uploaded it, fetched it BACK
// from the image host, and matched the SHA-256. If a single reference fails
// that test, this script writes NOTHING AT ALL and exits 1. A partial rewrite
// is a page of mixed working and broken photographs, which is harder to notice
// and harder to undo than a rewrite that did not happen.
//
// NOT RUN YET. image-manifest.json does not exist, because Task 4's migration
// cannot run until the R2 custom domain is connected -- see
// docs/cloudflare-cutover.md §21. Running this against a hand-written or
// partial manifest defeats the only safety property it has.
//
// WHAT IT DELIBERATELY DOES NOT TOUCH:
//
//   The share card at the site root. src/content/site.json's seo.ogImage.
//     src/components/SeoHead.tsx and worker/post-seo.ts turn it absolute by
//     resolving it against site.seo.url; it is generated by
//     scripts/images.mjs's encodeOgImage rather than by outputPathFor, so it
//     was never part of the derivative set this migration moved. Link
//     unfurlers fetch it from this origin and will keep doing so. This is the
//     one reference that makes the content census 69 and the content rewrite
//     68.
//
//   The two menu PDFs -- Task 19's population, moved with their upload path.
//
//   The favicons, the apple touch icon and the PWA icons -- referenced from
//     index.html, not from content, and browsers and PWA manifests expect them
//     at the site root.
//
// HOW THE JSON IS WRITTEN, and this is a deviation from the plan that had to
// happen. The plan wrote the content files back with
// `JSON.stringify(value, null, 2)`. Measured against the real tree: four of
// the twelve files (dishes, menus, pages, site) are hand-authored with compact
// inline objects and arrays, and re-stringifying them reformats every one --
// menus.json alone goes from 157 bytes to 185. That would bury a
// seventy-seven-reference rewrite, already the riskiest commit in this plan,
// under an unrelated whitespace diff, and it would change the exact bytes the
// D1 floor and the weekly export are later compared against. So the JSON is
// edited as TEXT and then checked structurally: the result is re-parsed and
// must deep-equal what the structural walk said it should be, or the file is
// refused. Formatting survives and the edit is still proved exact.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const CONTENT_DIR = join('src', 'content');

// Duplicated from src/shared/image-host.ts rather than imported: this script
// is plain `node`, and that module is TypeScript. The two strings are pinned
// equal by scripts/__tests__/rewrite-image-refs.test.mjs, which imports both.
//
// A PREFIX, NOT A HOST, since the owner chose to serve photographs from the
// main domain rather than from img.viabiancarestaurant.com. That changes what
// this script produces -- `/images/food/x.webp` instead of a whole https URL
// -- and it changes nothing else about it: the same references move, the same
// manifest gates them, the same refusal-before-writing applies.
const BASE = '/images';

// Exported so its own test can pin it against docs/image-inventory.json's
// census rather than against a second copy of this list. A list restated in
// the test is a list nothing checks: dropping the stylesheet from here left
// the whole suite green until that pin existed, and the stylesheet carries the
// body::before texture, which is the single most visible image on the site.
export const CODE_FILES = [
  'src/index.css',
  'src/components/Hero.tsx',
  'src/components/ChefGallery.tsx',
  'src/components/SignatureMocktails.tsx',
  'src/content/types.ts',
];

const KEEP = new Set(['/og-image.jpg']);
// `BASE + '/'` is in this list, and it is what makes a second run a no-op.
//
// While the destination was a whole https URL, that property came free:
// ASSET_PATH_PATTERN only matches a path starting with a slash, so an
// already-rewritten reference was invisible to this script. The destination is
// a path now, and `/images/food/x.webp` matches that pattern perfectly well --
// so without this line a second run would produce `/images/images/food/x.webp`
// wherever the manifest happened to say yes.
//
// The real manifest says no (there is no `images/food/x.webp` key in it), so a
// re-run would be REFUSED rather than doubled -- which is loud, and survivable,
// and still not the property worth having. `stays()` is where "this reference
// is already where it belongs" is decided, and this is that decision.
//
// Nothing pre-migration lives under this prefix: public/ has no `images`
// directory, and docs/image-inventory.json's census is the list of what
// actually exists.
const KEEP_PREFIX = [BASE + '/', '/menus/', '/favicon', '/apple-touch-icon', '/icon-'];

// `pdf` is in the pattern even though no PDF moves, and that is the point: a
// path this pattern does not match is a path `stays()` never sees, so the two
// menu PDFs would be left behind SILENTLY rather than reported as deliberate
// skips. The plan's own expected output says three references are left alone;
// without pdf here it would have printed one and nobody would have known which
// two were missing.
const ASSET_PATH_PATTERN = /^\/.+\.(jpg|jpeg|png|webp|avif|svg|pdf)$/i;

export function stays(path) {
  return KEEP.has(path) || KEEP_PREFIX.some((prefix) => path.startsWith(prefix));
}

export function emptyReport() {
  return { changed: [], skipped: [], missing: [], mapping: new Map() };
}

function target(path, manifest, report) {
  if (stays(path)) { report.skipped.push(path); return null; }
  const key = path.slice(1);
  const entry = manifest.objects[key];
  if (!entry || !entry.verifiedAt) { report.missing.push(path); return null; }
  report.changed.push(path);
  // encodeURI, not the raw key, and the same rule src/shared/image-host.ts's
  // imageUrl applies. Five filenames carry spaces and one an apostrophe. In a
  // CSS url() or a JSON string those have to arrive already encoded, or the
  // request goes to a different key than R2 holds -- and worker/images.ts
  // decodes the pathname it receives with the matching decodeURI, so the two
  // ends agree by construction rather than by luck.
  const moved = BASE + '/' + encodeURI(key);
  report.mapping.set(path, moved);
  return moved;
}

export function rewriteJson(value, manifest, report) {
  if (typeof value === 'string') {
    if (!ASSET_PATH_PATTERN.test(value)) return value;
    return target(value, manifest, report) ?? value;
  }
  if (Array.isArray(value)) return value.map((item) => rewriteJson(item, manifest, report));
  if (value !== null && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, rewriteJson(v, manifest, report)]));
  }
  return value;
}

// The formatting-preserving half. Every replacement is a whole JSON string
// token -- opening quote, path, closing quote -- so no path can be matched
// inside a longer one, and a path sitting in a KEY rather than a value would
// change the parsed shape and be caught by the check below.
// The walk fills a FRESH report per file and its findings are merged after.
// Sharing one mapping across files would apply an earlier file's replacements
// to a later one -- and a path shared between two files lives in the Map only
// once, so the second file's own occurrence would then never be replaced at
// all. Per-file, both halves are exact.
export function rewriteJsonText(text, manifest, report) {
  const local = emptyReport();
  const expected = rewriteJson(JSON.parse(text), manifest, local);
  let out = text;
  for (const [from, to] of local.mapping) {
    out = out.split(JSON.stringify(from)).join(JSON.stringify(to));
  }
  if (JSON.stringify(JSON.parse(out)) !== JSON.stringify(expected)) {
    throw new Error('the text edit did not reproduce the structural rewrite');
  }
  report.changed.push(...local.changed);
  report.skipped.push(...local.skipped);
  report.missing.push(...local.missing);
  for (const [from, to] of local.mapping) report.mapping.set(from, to);
  return out;
}

// The code half. Matches a quoted or url()-wrapped site-root path -- the same
// expression scripts/image-inventory.mjs's CODE_ASSET_PATTERN uses -- and
// replaces it in place, so a .tsx attribute, a .css url() and a doc comment
// are all handled by one function and none of them can be forgotten.
export function rewriteSource(text, manifest, report) {
  return text.replace(/(["'`(])(\/[^"'`()\n]+\.(?:jpg|jpeg|png|webp|avif|svg|pdf))(["'`)])/gi,
    (whole, open, path, close) => {
      const replaced = target(path, manifest, report);
      return replaced === null ? whole : open + replaced + close;
    });
}

export function plan(readFile, manifest, report, {
  contentDir = CONTENT_DIR, contentFiles, codeFiles = CODE_FILES,
} = {}) {
  if (!Array.isArray(contentFiles)) {
    throw new Error('plan() needs the list of content files; a missing list would silently rewrite only the code half');
  }
  const pending = [];
  for (const name of contentFiles) {
    const file = join(contentDir, name);
    const before = readFile(file);
    const after = rewriteJsonText(before, manifest, report);
    if (after !== before) pending.push({ file, after });
  }
  for (const file of codeFiles) {
    const before = readFile(file);
    const after = rewriteSource(before, manifest, report);
    if (after !== before) pending.push({ file, after });
  }
  return pending;
}

if (import.meta.filename === process.argv[1]) {
  const manifest = JSON.parse(readFileSync('image-manifest.json', 'utf-8'));
  const report = emptyReport();
  const pending = plan((file) => readFileSync(file, 'utf-8'), manifest, report, {
    contentFiles: readdirSync(CONTENT_DIR).filter((n) => n.endsWith('.json')),
  });

  console.log(`rewrite: ${report.changed.length} references, ${report.skipped.length} deliberately left alone`);
  for (const path of [...new Set(report.skipped)]) console.log(`  keep    ${path}`);

  if (report.missing.length > 0) {
    console.error(`\nREFUSING TO WRITE. ${report.missing.length} reference(s) name an object that is not verified in image-manifest.json:`);
    for (const path of report.missing) console.error(`  ${path}`);
    console.error('\nRun `npm run migrate:images` until every object reports verified, then run this again.');
    process.exit(1);
  }

  for (const { file, after } of pending) writeFileSync(file, after);
  console.log(`\nwrote ${pending.length} files`);
}
