// Regenerates worker/snapshot.ts from the LIVE D1 database, so the fallback
// the Worker compiles in is the content that was actually serving, not a
// hand-maintained copy that drifts.
//
// Source is D1, not src/content/*.json: src/content/awards.json has never
// existed as a repo file (worker/store.ts's D1_ONLY_PATHS names it as the
// one path that lives nowhere else), so a generator that walked
// src/content/*.json would find nothing for the only file the public read
// path actually serves. This queries the `content` table directly instead --
// see worker/d1.ts's D1Store for the table this reads.
//
// Run by a human before a deploy that matters:
//   node scripts/build-snapshot.mjs
//
// Not a build step, deliberately. Making it one would put a `wrangler d1
// execute` (an authenticated network call) on Cloudflare Pages' own build
// path, where a transient failure would fail a deploy of unrelated code --
// and Pages builds in this project are already intermittently flaky enough
// that three consecutive builds failed on unchanged, working source.
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const DB = 'via-bianca-content';
const raw = execFileSync('npx', [
  'wrangler', 'd1', 'execute', DB, '--remote', '--json',
  '--command', 'SELECT path, body, version FROM content',
], { encoding: 'utf8' });

const rows = JSON.parse(raw)[0]?.results ?? [];
if (rows.length === 0) throw new Error('refusing to write an empty snapshot -- is the database seeded?');

// Keyed on the PUBLIC filename (worker/published.ts's PUBLIC_FILES maps
// `awards.json` -> `src/content/awards.json`), not the repo-relative path --
// `snapshotFor` is called with the same public name the Worker already
// strips `path` down to before it ever reaches this module.
const entries = Object.fromEntries(
  rows.map((row) => [
    row.path.replace(/^src\/content\//, ''),
    { body: row.body, version: row.version },
  ]),
);

const builtAt = new Date().toISOString();

writeFileSync(
  'worker/snapshot.ts',
  `// GENERATED by scripts/build-snapshot.mjs from the live D1 database. Do not\n` +
    `// edit by hand -- regenerate with \`node scripts/build-snapshot.mjs\` before a\n` +
    `// deploy that matters.\n` +
    `//\n` +
    `// The last-known-good content, compiled into the Worker bundle. If a D1\n` +
    `// query fails or times out, worker/published.ts serves this instead. A\n` +
    `// database outage costs freshness; it never costs availability.\n` +
    `//\n` +
    `// Each entry also carries the \`version\` D1 held for that path at generation\n` +
    `// time -- the same monotonic counter worker/d1.ts bumps on every write and\n` +
    `// worker/published.ts's own cache key is built from. D1Store.write never\n` +
    `// reuses a version number for different content and never decreases it (an\n` +
    `// undo is itself a write through the same guard), so a version match against\n` +
    `// the live database is proof the body is still identical -- which is what\n` +
    `// lets a later check compare a cheap single-column read against this\n` +
    `// snapshot instead of pulling and diffing the whole body, and tell a\n` +
    `// snapshot that still matches what's serving from one that has quietly gone\n` +
    `// stale.\n` +
    `export const SNAPSHOT_BUILT_AT = ${JSON.stringify(builtAt)};\n\n` +
    `interface SnapshotEntry {\n` +
    `  body: string;\n` +
    `  version: number;\n` +
    `}\n\n` +
    `const SNAPSHOT: Record<string, SnapshotEntry> = ${JSON.stringify(entries, null, 2)};\n\n` +
    `export function snapshotFor(file: string): string | null {\n` +
    `  return Object.prototype.hasOwnProperty.call(SNAPSHOT, file) ? SNAPSHOT[file].body : null;\n` +
    `}\n\n` +
    `// The D1 \`version\` this file's body was captured at -- see the header\n` +
    `// comment above for what a later comparison against it can prove.\n` +
    `export function snapshotVersionFor(file: string): number | null {\n` +
    `  return Object.prototype.hasOwnProperty.call(SNAPSHOT, file) ? SNAPSHOT[file].version : null;\n` +
    `}\n`,
);
console.log(`snapshot: ${Object.keys(entries).length} document(s), built ${builtAt}`);
